// Writes each weekday's Campfire into SQL for the online game's server (table public.campfire_days).
// Sources (never edit the output by hand; change these, then rerun and load again):
// - src/data/campfireDaysData.ts (canon Campfire v2.3: opener, fork, callback, riddle, nudge, tone, cup night)
// - src/data/fanOutLeads.ts (the approved Fan Out leads and late lines)
// - src/data/fragmentMeaningQuestions.ts, src/data/weekQuestions.ts
// - src/data/chapterScripts.ts (the day's Pull)
// QA-only fields (leans, bearsOnFork, qaNote) are left out: they never reach a player.
// Run: npx tsx scripts/gen-campfire-sql.ts <week> > supabase/migrations/00NN_campfire_week<week>.sql
import { CAMPFIRE_DAYS_DATA } from '../src/data/campfireDaysData';
import { APPROVED_FAN_OUT_LEADS, lateLineFor } from '../src/data/fanOutLeads';
import { FRAGMENT_MEANING_QUESTIONS } from '../src/data/fragmentMeaningQuestions';
import { WEEK_QUESTIONS } from '../src/data/weekQuestions';
import { CHAPTER_SCRIPTS } from '../src/data/chapterScripts';

const week = Number(process.argv[2]);
if (!week) throw new Error('usage: gen-campfire-sql.ts <week> [--json]');
const asJson = process.argv.includes('--json'); // rows as JSON, for a one-time loader
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const rows = CAMPFIRE_DAYS_DATA.filter((d) => d.week === week).map((d) => {
  const key = `${d.week}-${d.day}`;
  const leads = (APPROVED_FAN_OUT_LEADS[key] || []).map((l) => ({
    id: l.id,
    place: l.place,
    actions: l.actions,
    clueTitle: l.clueTitle,
    clueText: l.clueText,
    hintFor: l.hintFor,
    lateLine: l.lateLine || lateLineFor(d.week, d.day),
  }));
  if (leads.length === 0) throw new Error(`no approved leads for ${key}`);
  const script = CHAPTER_SCRIPTS.find((c) => c.week === d.week && c.day === d.day);
  const pull = script?.steps.find((s) => s.t === 'say' && s.pull);
  const data = {
    place: d.place,
    narrated: d.narratedNoGarrick,
    tone: d.tone,
    cupNight: d.cupNight,
    opener: d.opener,
    forkA: d.forkA,
    forkB: d.forkB,
    callback: d.callback,
    nudge: d.nudge,
    riddle: d.riddle ? { q: d.riddle.q, a: d.riddle.a, quip: d.riddle.quip, accept: d.riddle.accept, maxTries: d.riddle.maxTries } : null,
    leads,
    meaningQuestion: FRAGMENT_MEANING_QUESTIONS[key] ?? null,
    weekQuestion: WEEK_QUESTIONS[d.week] ?? null,
    pull: pull && pull.t === 'say' ? pull.text : null,
  };
  return { week: d.week, day: d.day, data };
});

if (asJson) {
  console.log(JSON.stringify(rows));
  process.exit(0);
}
const values = rows.map((r) => `('dark-moon', 1, ${r.week}, ${r.day}, ${q(JSON.stringify(r.data))}::jsonb)`);

console.log(`-- The Campfire for Week ${week}, generated by scripts/gen-campfire-sql.ts. Do not edit by hand.
insert into public.campfire_days (series_id, season_number, week, day, data) values
${values.join(',\n')}
on conflict (series_id, season_number, week, day) do update set data = excluded.data;`);
