// Writes the weekday chapters into an SQL migration for the online game's server (table public.chapters).
// The server hands each chapter out only on its day, so no phone holds the season's later text.
// Run: npx tsx scripts/gen-chapters-sql.ts <week> > supabase/migrations/00NN_chapters_week<week>.sql
import { CHAPTER_SCRIPTS } from '../src/data/chapterScripts';
import { WEEKDAY_INVENTORY } from '../src/data/mythiosChaptersData';
import { EPISODE_NUMBERS } from '../src/data/mythiosRulesData';

const week = Number(process.argv[2]);
if (!week) throw new Error('give a week number');
const ep = EPISODE_NUMBERS.find((e) => e.week === week)!;
const rows = CHAPTER_SCRIPTS.filter((c) => c.week === week).map((c) => {
  const inv = WEEKDAY_INVENTORY.find((d) => d.week === c.week && d.day === c.day);
  const meta = { dc: ep.weekdayDC, wDef: ep.wDef, wAtk: ep.wAtk, fightReward: inv?.fightReward ?? 0 };
  const q = (v: unknown) => `$json$${JSON.stringify(v)}$json$::jsonb`;
  return `('dark-moon', 1, ${c.week}, ${c.day}, ${q(c)}, ${q(meta)})`;
});
console.log(`-- Week ${week}'s chapters for the online game, generated by scripts/gen-chapters-sql.ts from src/data/chapterScripts.ts
-- (itself generated from docs/canon/episode-${week}-*.md). Do not edit by hand.
insert into public.chapters (series_id, season_number, week, day, script, meta) values
${rows.join(',\n')}
on conflict (series_id, season_number, week, day) do update set script = excluded.script, meta = excluded.meta;`);
