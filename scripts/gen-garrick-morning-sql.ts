// Writes Garrick's morning lines into an SQL migration for the online game's server (table public.garrick_morning_lines).
// Refuses until Fake Guru has approved them (GARRICK_MORNING_APPROVED in src/data/garrickMorningLines.ts).
// Run: npx tsx scripts/gen-garrick-morning-sql.ts > supabase/migrations/00NN_garrick_morning_lines.sql
import { GARRICK_MORNING_APPROVED, GARRICK_MORNING_LINES } from '../src/data/garrickMorningLines';

if (!GARRICK_MORNING_APPROVED) {
  console.error('Not approved yet: Garrick\'s morning lines wait for Fake Guru.');
  process.exit(1);
}
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = GARRICK_MORNING_LINES.map((l) => `('dark-moon', 1, ${l.week}, ${l.day}, ${q(l.line)})`);
console.log(`-- Garrick's morning lines for the online game, generated by scripts/gen-garrick-morning-sql.ts from
-- src/data/garrickMorningLines.ts (approved by Fake Guru). Do not edit by hand.
insert into public.garrick_morning_lines (series_id, season_number, week, day, line) values
${rows.join(',\n')}
on conflict (series_id, season_number, week, day) do update set line = excluded.line;`);
