// Writes the 36 Seeker Fragments into an SQL migration for the online game's server (table public.fragments).
// Run: npx tsx scripts/gen-fragments-sql.ts > supabase/migrations/0020_fragments_data.sql
import { SEEKER_FRAGMENTS } from '../src/data/mythiosFragments';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(',')}]`;
const rows = SEEKER_FRAGMENTS.map(
  (f) =>
    `('dark-moon', 1, ${q(f.id)}, ${f.week}, ${f.day}, ${q(f.placeLabel)}, ${q(f.displayTemplate)}, ${q(f.word1)}, ${arr(f.jumble1)}, ${q(f.word2)}, ${arr(f.jumble2)})`
);
console.log(`-- The 36 Seeker Fragments for the online game, generated by scripts/gen-fragments-sql.ts from src/data/mythiosFragments.ts.
-- Do not edit by hand.
insert into public.fragments (series_id, season_number, id, week, day, place_label, template, word1, jumble1, word2, jumble2) values
${rows.join(',\n')}
on conflict (series_id, season_number, id) do update set place_label = excluded.place_label, template = excluded.template,
  word1 = excluded.word1, jumble1 = excluded.jumble1, word2 = excluded.word2, jumble2 = excluded.jumble2;`);
