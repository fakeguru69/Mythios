// The game's rhythm, measured from the data the game plays: how much story a player reads between taps, which taps
// are real decisions, and roughly how long each part takes. For the gameplay-quality audit (docs/playthrough/
// gameplay-audit-prompt.md), so a reviewer can judge "point to point" against numbers, not impressions.
// Run: npx tsx scripts/gen-gameplay-rhythm.ts  → docs/playthrough/gameplay-rhythm.md
// Path measured: the main path (Challenge passed, fight won, [PRESS ON] left, the first option of a choice; every
// branch of an "each" choice). Reading speed 230 words a minute. Fight rounds from docs/numbers-pass-15oct.md.
import fs from 'fs';
import { CHAPTER_SCRIPTS, type ScriptStep } from '../src/data/chapterScripts';
import { GATHERING_SCRIPTS, type GatheringStep } from '../src/data/gatheringScripts';
import { CAMPFIRE_DAYS_DATA } from '../src/data/campfireDaysData';
import { APPROVED_FAN_OUT_LEADS } from '../src/data/fanOutLeads';

const WPM = 230;
const words = (t: string) => t.replace(/[*_`#>]/g, ' ').split(/\s+/).filter(Boolean).length;
// A weekday fight: 3–5 rounds in Week 1, 4–6 in Weeks 2–4, 5–6 in Weeks 5–6 (numbers pass, player striking first).
const FIGHT_TAPS: Record<number, number> = { 1: 4, 2: 5, 3: 5, 4: 5, 5: 6, 6: 6 };

type Beat = { kind: 'read'; w: number } | { kind: 'tap' | 'flavor' | 'choice' | 'roll' | 'fight' | 'optional'; label: string; taps: number };

function chapterBeats(steps: ScriptStep[], week: number): Beat[] {
  const out: Beat[] = [];
  const read = (n: number) => {
    const last = out[out.length - 1];
    if (last && last.kind === 'read') last.w += n;
    else out.push({ kind: 'read', w: n });
  };
  for (const s of steps) {
    if (s.t === 'say') {
      if (s.cond && !((s.cond.on === 'challenge' && s.cond.pass) || (s.cond.on === 'fight' && s.cond.won))) continue;
      read(words(s.text));
    } else if (s.t === 'act') out.push({ kind: 'tap', label: s.label, taps: 1 });
    else if (s.t === 'choice') {
      // 'auto' is "you look at one, friends take the rest": the player still picks, and the branches differ (W2D2, W2D5).
      const real = (s.mode === 'pick' || s.mode === 'auto') && s.branches.length > 0;
      out.push({ kind: s.mode === 'flavor' ? 'flavor' : real ? 'choice' : 'tap', label: `${s.labels.join(' / ')} (${s.mode})`, taps: s.mode === 'each' ? s.labels.length : 1 });
      const shown = s.mode === 'pick' || s.mode === 'flavor' ? s.branches.slice(0, 1) : s.branches;
      shown.forEach((b) => read(words(b.text)));
    } else if (s.t === 'notice') {
      const first = Object.values(s.lines)[0];
      if (first) read(words(first.first) + words(first.second ?? ''));
    } else if (s.t === 'challenge') {
      read(words(s.desc));
      out.push({ kind: 'roll', label: `CHALLENGE: ${s.title} (${s.options.map((o) => o.attr).join(' or ')})`, taps: 2 });
    } else if (s.t === 'press') out.push({ kind: 'optional', label: `[PRESS ON] ${s.title}`, taps: 1 });
    else if (s.t === 'fight') {
      read(words(s.desc) + (s.firstLines ? words(s.firstLines[0]) : 0));
      out.push({ kind: 'fight', label: `FIGHT: ${s.name}`, taps: FIGHT_TAPS[week] });
    } else if (s.t === 'summary') read(s.lines.reduce((n, l) => n + words(l), 0));
  }
  return out;
}

const glyph = (b: Beat) =>
  b.kind === 'read' ? `${b.w}w` : { tap: '▸tap', flavor: '◇flavour', choice: '◆CHOICE', roll: '🎲CHALLENGE', fight: '⚔FIGHT', optional: '?PRESS ON' }[b.kind];

const lines: string[] = [];
const w = (...l: string[]) => lines.push(...l, '');
w(
  '# Tales of the Dark Moon: the rhythm of play, measured',
  'Generated by `scripts/gen-gameplay-rhythm.ts` from the data the game plays. Read it beside the play-through files.',
  '',
  '**How to read it.** Each weekday chapter is shown as a strip: `120w` is 120 words of story read before the next thing to do; `▸tap` is a button that only moves the story on; `◇flavour` is a choice whose options all lead to the same text; `◆CHOICE` is a choice whose branches differ; `🎲CHALLENGE` is the day\'s roll (pick an Attribute, roll); `⚔FIGHT` is a fight (one tap a round); `?PRESS ON` is the optional harder roll after a pass.',
  '',
  `Measured on the main path: Challenge passed, fight won, [PRESS ON] left, the first option of each choice. Reading at ${WPM} words a minute; a tap or a roll counted at about 4 seconds, a fight round at about 6 (the roll pause).`
);

w('## The weekday chapters');
lines.push('| Day | Words | Taps | Real choices | Flavour choices | Longest read before a tap | Read time | Strip |', '|---|---|---|---|---|---|---|---|');
const dayRows: { key: string; words: number; taps: number; mins: number }[] = [];
for (const ch of CHAPTER_SCRIPTS) {
  const beats = chapterBeats(ch.steps, ch.week);
  const reads = beats.filter((b) => b.kind === 'read') as { kind: 'read'; w: number }[];
  const total = reads.reduce((n, b) => n + b.w, 0);
  const taps = beats.filter((b) => b.kind !== 'read').reduce((n, b) => n + (b as { taps: number }).taps, 0);
  const real = beats.filter((b) => b.kind === 'choice').length;
  const flavor = beats.filter((b) => b.kind === 'flavor').length;
  const longest = Math.max(...reads.map((b) => b.w));
  const fightTaps = beats.filter((b) => b.kind === 'fight').reduce((n, b) => n + (b as { taps: number }).taps, 0);
  const mins = total / WPM + ((taps - fightTaps) * 4 + fightTaps * 6) / 60;
  dayRows.push({ key: `W${ch.week}D${ch.day}`, words: total, taps, mins });
  lines.push(`| W${ch.week}D${ch.day} | ${total} | ${taps} | ${real} | ${flavor} | ${longest}w | ${mins.toFixed(1)} min | ${beats.map(glyph).join(' ')} |`);
}
lines.push('');
const avg = (k: 'words' | 'taps' | 'mins') => dayRows.reduce((n, r) => n + r[k], 0) / dayRows.length;
w(`**Averages over the 36 chapters:** ${Math.round(avg('words'))} words, ${avg('taps').toFixed(1)} taps, about ${avg('mins').toFixed(1)} minutes for the chapter alone (the last light and the Campfire come after).`);

// The evening: the last light and the Campfire.
w(
  '## The evening (every weekday after the chapter)',
  'The last light: three leads, pick one, roll (a pass gives the first letter of a fragment word; the clue comes back either way), or sit by the fire. Then the fire: one chat under the finished day (18 Oct), with a text box at the foot.',
);
lines.push('| Day | Leads | Garrick\'s stored lines (words) | Things to tap or write at the fire |', '|---|---|---|---|');
for (const d of CAMPFIRE_DAYS_DATA) {
  const leads = (APPROVED_FAN_OUT_LEADS[`${d.week}-${d.day}`] || []).length;
  const gw = words(d.opener ?? '') + words(d.callback ?? '') + words(d.nudge ?? '');
  // The riddle and the message in a bottle were cut on 18 Oct; the case so far moved to the Bag's casebook.
  const forms = ['tonight\'s question (pin A / B / neither; changeable until dawn)', 'the fragment\'s meaning question', 'lay a clue on the table (+)', 'Agree / Doubt on a friend\'s clue', 'talk in the chat', ...(d.clicks?.length ? [`${d.clicks.length} click${d.clicks.length > 1 ? 's' : ''} to find`] : [])];
  lines.push(`| W${d.week}D${d.day} | ${leads} | ${gw} | ${forms.length}: ${forms.join('; ')} |`);
}
lines.push('');

// The Gatherings.
w('## The Gatherings', 'Measured on the main path (Approach passed, United Effort won, the first option of each group choice). Besides the buttons counted here, the story moves passage by passage with [GO ON] (any friend taps it, or it moves on by itself); those taps are not counted.');
lines.push('| Week | Story words | Taps to move on | Group decisions | Rolls | Match | Ask questions | Table question | Read time |', '|---|---|---|---|---|---|---|---|---|');
for (const g of GATHERING_SCRIPTS) {
  let wordsRead = 0, acts = 0, picks = 0, rolls = 0, match = 0, ask = 0, turn = 0;
  for (const s of g.steps as GatheringStep[]) {
    const c = s.cond as { on?: string; pass?: boolean; won?: boolean; option?: number } | undefined;
    const onPath = !c || (c.on === 'approach' && c.pass) || (c.on === 'ue' && c.won) || (c.on === 'pick' && c.option === 0);
    if (!onPath) continue;
    if (s.t === 'say') wordsRead += words(s.text);
    else if (s.t === 'act') acts++;
    else if (s.t === 'pick') picks++;
    else if (s.t === 'approach' || s.t === 'ue' || s.t === 'lookCloser') rolls++;
    else if (s.t === 'match') match++;
    else if (s.t === 'ask') ask += s.rows.length;
    else if (s.t === 'turn') turn++;
    else if (s.t === 'battle') wordsRead += words(s.desc);
  }
  lines.push(`| ${g.week} | ${wordsRead} | ${acts} | ${picks} | ${rolls} (+ the Battle) | ${match} | ${ask} | ${turn} | ${(wordsRead / WPM).toFixed(0)} min reading |`);
}
lines.push('');

fs.writeFileSync('docs/playthrough/gameplay-rhythm.md', lines.join('\n'));
console.log('wrote docs/playthrough/gameplay-rhythm.md');
